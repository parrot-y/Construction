import { chromium } from 'playwright-core';
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', headless: true });
const page = await (await browser.newContext({viewport:{width:1440,height:900}})).newPage();
await page.goto('https://console.buildsasa.com/', {waitUntil:'domcontentloaded',timeout:30000});
await page.waitForTimeout(3000);
await page.click('button:has-text("contractor or service provider")');
await page.waitForTimeout(4000);
console.log('URL:', page.url());
console.log(await page.evaluate(()=>document.body.innerText.slice(0,2000)));
console.log('---INPUTS---');
console.log(await page.evaluate(()=>[...document.querySelectorAll('input,button,a')].map(e=>`${e.tagName}:${e.type||''}:${(e.innerText||e.placeholder||e.name||'').slice(0,60)}`).join('\n')));
await page.screenshot({path:'/tmp/refstudy/02-contractor-gate.png'});
await browser.close();
